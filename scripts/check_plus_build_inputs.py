#!/usr/bin/env python3
"""Check that every file path referenced by the Plus CMake files exists.

ES-IDE and CMake only fail on a missing source once compilation starts, which is
late and noisy. This walks the component `CMakeLists.txt` files, expands the
project-relative variables they use (`APP_ROOT`, `DEPENDENCY_ROOT`, `SDK_ROOT`,
`USB_DEPS`, `CMAKE_CURRENT_LIST_DIR`) and reports anything missing before a build.

Generated inputs are skipped, because they are produced by the resource and USB
preparation steps:
  * `generated/`      i18n tables and embedded HTML
  * `.local/jpegdec-plus`  the derived JPEGDEC copy
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "firmware/rickyos-plus-1.2"

VARIABLE = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}(\/[^\"\s]*)")
ASSIGNMENT = re.compile(r"set\(\s*([A-Za-z_][A-Za-z0-9_]*)\s+\"([^\"]+)\"\s*\)")

# Generated by the resource/USB preparation steps, or supplied only for the
# opt-in private Wi-Fi diagnostic profile.
GENERATED = ("generated/", ".local/jpegdec-plus", ".local/plus-private-wifi-test")


def expand(token: str, variables: dict[str, Path], current: Path) -> Path | None:
    match = VARIABLE.fullmatch(token)
    if not match:
        return None
    name, rest = match.groups()
    if name == "CMAKE_CURRENT_LIST_DIR":
        base = current
    elif name in variables:
        base = variables[name]
    else:
        return None
    return (base / rest.lstrip("/")).resolve()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    missing: list[tuple[Path, Path]] = []
    checked = 0
    for cmake in sorted(PROJECT.rglob("CMakeLists.txt")):
        if "upstream" in cmake.parts:
            continue
        text = cmake.read_text(encoding="utf-8", errors="replace")
        current = cmake.parent
        variables: dict[str, Path] = {}
        for name, value in ASSIGNMENT.findall(text):
            resolved = expand(value, variables, current)
            if resolved is not None:
                variables[name] = resolved
        for name, rest in VARIABLE.findall(text):
            if "*" in rest or "$" in rest:
                continue
            resolved = expand("${%s}%s" % (name, rest), variables, current)
            if resolved is None:
                continue
            relative = resolved.as_posix()
            if any(marker in relative for marker in GENERATED):
                continue
            checked += 1
            if not resolved.exists():
                missing.append((cmake, resolved))

    if missing:
        print(f"Missing {len(missing)} of {checked} referenced paths:")
        for cmake, path in missing:
            print(f"  {cmake.relative_to(ROOT)}: {path}")
        raise SystemExit(1)
    print(f"All {checked} referenced build inputs exist.")


if __name__ == "__main__":
    main()
